#!/usr/bin/env python3
"""Generate src/thresholds.rs and the §7 table of docs/specs/input-events.md from thresholds.toml.

Usage: thresholds.py [--check]
thresholds.toml is the one source of the input thresholds: each [[constant]] becomes a Rust constant
with its doc comment, and each [[row]] a row of the spec's table, between its generated markers.
--check exits 1 when a committed file differs from what the data generates.
"""
import argparse
import pathlib
import re
import sys
import tomllib

CRATE = pathlib.Path(__file__).resolve().parent.parent
DATA = CRATE / "thresholds.toml"
RUST = CRATE / "src" / "thresholds.rs"
SPEC = CRATE.parent.parent / "docs" / "specs" / "input-events.md"
BEGIN = "<!-- >>> thresholds.py: generated from crates/opendap-input/thresholds.toml; edit it, not this table -->"
END = "<!-- <<< thresholds.py -->"
HEADER = """\
// @generated by crates/opendap-input/tools/thresholds.py from crates/opendap-input/thresholds.toml.
// Do not edit: change the data file and run the tool (the table of input events §7 comes from it too).
"""
TYPES = {"u64": int, "f32": float, "f64": float}
FIELD = re.compile(r"\{([A-Z0-9_]+)(?:\|(s|per_s))?\}")


def load():
    return tomllib.loads(DATA.read_text())


def lines(text):
    return text.strip("\n").splitlines()


def rust_value(c):
    if "same_as" in c:
        return c["same_as"]
    v = c["value"]
    if not isinstance(v, TYPES[c["type"]]) or isinstance(v, bool):
        raise ValueError(f"{c['name']}: {v!r} is not a {c['type']}")
    return repr(v)


def render_rust(data):
    out = [HEADER.rstrip("\n")]
    out += [f"//! {line}".rstrip() for line in lines(data["module_doc"])]
    for c in data["constant"]:
        doc = lines(c.get("doc", ""))
        if doc:  # an undocumented constant belongs to the group of the one before it
            out.append("")
        out += [f"/// {line}".rstrip() for line in doc]
        out.append(f"pub const {c['name']}: {c['type']} = {rust_value(c)};")
    return "\n".join(out) + "\n"


def number(v):
    return str(int(v)) if float(v).is_integer() else repr(float(v))


def values(data):
    by_name = {c["name"]: c for c in data["constant"]}

    def value(name):
        c = by_name[name]
        return value(c["same_as"]) if "same_as" in c else c["value"]

    return value


def render_table(data):
    value = values(data)

    def field(m):
        v = value(m.group(1))
        return number({None: v, "s": v / 1000, "per_s": 1000 / v}[m.group(2)])

    out = ["| Threshold | Default | From |", "|---|---|---|"]
    out += [f"| {r['threshold']} | {FIELD.sub(field, r['default'])} | {r['from']} |" for r in data["row"]]
    return "\n".join(out) + "\n"


def splice(doc, table):
    head, sep, rest = doc.partition(BEGIN + "\n")
    _, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        raise ValueError(f"{SPEC}: the generated markers are missing")
    return head + BEGIN + "\n" + table + END + tail


def outputs(data):
    return {RUST: render_rust(data), SPEC: splice(SPEC.read_text(), render_table(data))}


def stale():
    return [p for p, text in outputs(load()).items() if p.read_text() != text]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if args.check:
        for p in stale():
            print(f"{p} is not what {DATA} generates: run thresholds.py", file=sys.stderr)
        return 1 if stale() else 0
    for p, text in outputs(load()).items():
        p.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
