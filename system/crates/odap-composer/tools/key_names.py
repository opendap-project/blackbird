#!/usr/bin/env python3
"""Generate src/linux/key_names.rs from the kernel's uapi header linux/input-event-codes.h.

Usage: key_names.py [--header PATH] [--check]
The header comes from the Blackbird OS sysroot (`odapkit sysroot path`), or --header. Every `#define KEY_<NAME>
<code>` gives a name; where the header gives a code several names, the first one is used; KEY_MAX, KEY_CNT and
KEY_MIN_INTERESTING are limits, not keys. --check exits 1 when the committed file differs, and 0 with a notice
when no header is available (no sysroot on this host).
"""
import argparse
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "linux" / "key_names.rs"
DEFINE = re.compile(r"^#define\s+(KEY_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\b")
LIMITS = {"KEY_MAX", "KEY_CNT", "KEY_MIN_INTERESTING", "KEY_RESERVED"}
HEADER = """\
// @generated by crates/odap-composer/tools/key_names.py from the kernel's uapi header
// linux/input-event-codes.h in the Blackbird OS sysroot (toolkit-image odapkit-sysroot). Do not edit;
// regenerate when the kernel adds codes. Where the header gives a code several names, the first is used.
"""


def names(header_text):
    seen = {}
    for line in header_text.splitlines():
        m = DEFINE.match(line)
        if not m or m.group(1) in LIMITS:
            continue
        code = int(m.group(2), 0)
        seen.setdefault(code, m.group(1))
    return sorted(seen.items())


def render(pairs):
    body = "".join(f'    ({code}, "{name}"),\n' for code, name in pairs)
    return HEADER + "pub const KEY_NAMES: &[(u32, &str)] = &[\n" + body + "];\n"


def sysroot_header():
    try:
        root = subprocess.run(["odapkit", "sysroot", "path"], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None
    p = pathlib.Path(root) / "usr/include/linux/input-event-codes.h"
    return p if p.is_file() else None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--header")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    header = pathlib.Path(args.header) if args.header else sysroot_header()
    if header is None:
        print("key_names.py: no input-event-codes.h (no sysroot on this host): not checked", file=sys.stderr)
        return 0
    text = render(names(header.read_text()))
    if args.check:
        if OUT.read_text() == text:
            return 0
        print(f"{OUT} is not what {header} generates: run key_names.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
