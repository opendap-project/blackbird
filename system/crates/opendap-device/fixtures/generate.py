#!/usr/bin/env python3
"""Generate virtual-t1.toml, the test fixture of the virtual T1's device description, from virtual-devices.

Usage: generate.py [--check]
The description is what virtual-devices composes and hands to the guest (`odap-vdev describe`), found through
ODAP_VIRTUAL_DEVICES_DIR or the workspace's repos.tsv. --check exits 1 when the committed fixture differs, and 0
with a notice when no virtual-devices checkout is available.
"""
import os
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "virtual-t1.toml"
HEADER = """\
# @generated by fixtures/generate.py from virtual-devices (odap-vdev describe, model virtual-t1): the description
# the virtual board hands to the guest through fw_cfg. Do not edit; regenerate when the emulator's layers change.
"""


def virtual_devices():
    env = os.environ.get("ODAP_VIRTUAL_DEVICES_DIR")
    if env:
        return pathlib.Path(env)
    for p in (HERE, *HERE.parents):
        tsv = p / "repos.tsv"
        if tsv.is_file():
            for line in tsv.read_text().splitlines()[1:]:
                path, _, repo = line.partition("\t")
                if repo.endswith("/virtual-devices"):
                    return p / path
    return None


def main(argv=None):
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    vd = virtual_devices()
    tool = vd / "bin" / "odap-vdev" if vd else None
    if tool is None or not tool.is_file():
        print("generate.py: no virtual-devices checkout: fixture not checked", file=sys.stderr)
        return 0
    desc = subprocess.run([sys.executable, str(tool), "--model", "virtual-t1", "describe"], capture_output=True,
                          text=True, check=True).stdout
    text = HEADER + desc
    if check:
        if OUT.read_text() == text:
            return 0
        print(f"{OUT} is not what virtual-devices describes: run fixtures/generate.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
