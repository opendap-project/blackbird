//! Blackbird UI's published design tokens (`export/css/tokens.css`) as Rust constants, for build
//! scripts of crates that draw with a token themselves: colours as 8-bit sRGB, durations in ms.

use std::fmt::Write;
use std::path::Path;

/// The value of custom property `--name` in `css`.
pub fn value<'a>(css: &'a str, name: &str) -> Result<&'a str, String> {
    let key = format!("--{name}:");
    css.lines()
        .find_map(|l| l.trim().strip_prefix(&key))
        .and_then(|v| v.trim().strip_suffix(';'))
        .map(str::trim)
        .ok_or_else(|| format!("tokens.css has no --{name}"))
}

fn ident(name: &str) -> String {
    name.to_uppercase().replace('-', "_")
}

/// Rust source with one constant per token: `colours` (`#RRGGBB`) as `pub const <NAME>: [u8; 3]`,
/// `durations` (`<n>ms`) as `pub const <NAME>_MS: u64`.
pub fn rust_constants(css: &str, colours: &[&str], durations: &[&str]) -> Result<String, String> {
    let mut rs =
        String::from("// @generated by build.rs from Blackbird UI's export/css/tokens.css.\n");
    for name in colours {
        let v = value(css, name)?;
        let hex = v.strip_prefix('#').filter(|h| h.len() == 6);
        let hex = hex.ok_or_else(|| format!("--{name}: {v} is not #RRGGBB"))?;
        let c = |i: usize| u8::from_str_radix(&hex[i..i + 2], 16);
        let bad = |_| format!("--{name}: {v} is not #RRGGBB");
        let (r, g, b) = (c(0).map_err(bad)?, c(2).map_err(bad)?, c(4).map_err(bad)?);
        let id = ident(name);
        writeln!(
            rs,
            "/// `--{name}`: {v}.\npub const {id}: [u8; 3] = [{r:#04x}, {g:#04x}, {b:#04x}];"
        )
        .unwrap();
    }
    for name in durations {
        let v = value(css, name)?;
        let ms: u64 = v
            .strip_suffix("ms")
            .and_then(|n| n.parse().ok())
            .ok_or_else(|| format!("--{name}: {v} is not in ms"))?;
        let id = ident(name);
        writeln!(rs, "/// `--{name}`: {v}.\npub const {id}_MS: u64 = {ms};").unwrap();
    }
    Ok(rs)
}

/// For a build script: writes `out` (included with `include!`) from the tokens file `css_path`.
pub fn write_rust_constants(
    css_path: &Path,
    colours: &[&str],
    durations: &[&str],
    out: &Path,
) -> Result<(), String> {
    let css = std::fs::read_to_string(css_path).map_err(|e| format!("{css_path:?}: {e}"))?;
    let rs = rust_constants(&css, colours, durations)?;
    std::fs::write(out, rs).map_err(|e| format!("{out:?}: {e}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    const CSS: &str =
        ":root {\n  --bg: #111315;\n  --motion-duration-slow: 320ms;\n  --x: 4px;\n}\n";

    #[test]
    fn colours_and_durations_become_constants() {
        let rs = rust_constants(CSS, &["bg"], &["motion-duration-slow"]).unwrap();
        assert!(rs.contains("pub const BG: [u8; 3] = [0x11, 0x13, 0x15];"));
        assert!(rs.contains("pub const MOTION_DURATION_SLOW_MS: u64 = 320;"));
    }

    #[test]
    fn a_missing_or_malformed_token_is_an_error() {
        assert!(
            rust_constants(CSS, &["fg"], &[])
                .unwrap_err()
                .contains("--fg")
        );
        assert!(rust_constants(CSS, &["x"], &[]).is_err());
        assert!(rust_constants(CSS, &[], &["x"]).is_err());
    }
}
