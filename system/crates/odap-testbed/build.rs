// The design tokens, fonts and icons come from Blackbird UI's published outputs (its export/),
// found through ODAP_BLACKBIRD_DIR or the workspace's repos.tsv, never from its sources.
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let ui =
        opendap_workspace::repo_dir("blackbird-ui", &manifest).unwrap_or_else(|e| panic!("{e}"));
    let export = ui.join("export");
    for sub in ["slint", "fonts", "icons"] {
        if !export.join(sub).is_dir() {
            panic!(
                "{} not found: run blackbird-ui's generators (tokens/generate.py, icons/icons.py)",
                export.join(sub).display()
            );
        }
    }
    println!(
        "cargo:rerun-if-env-changed={}",
        opendap_workspace::env_var("blackbird-ui")
    );
    println!("cargo:rerun-if-changed={}", export.display());

    // Debug builds carry the element tree's debug info, so the interface tests (ADR 0014, L2) can
    // find elements by their accessible names; release builds, the ones that ship, do not.
    let debug = std::env::var("PROFILE").is_ok_and(|p| p == "debug");
    let generated = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    screens(&manifest.join("screens.tsv"), &generated);
    let config = slint_build::CompilerConfiguration::new()
        .with_library_paths(
            [
                ("blackbird".to_string(), export),
                ("testbed".to_string(), generated),
            ]
            .into(),
        )
        .with_debug_info(debug);
    slint_build::compile_with_config("ui/testbed.slint", config).unwrap();
}

/// The screens' list (screens.tsv: name, detail) as the interface's list (`ScreenList`, in
/// `@testbed/screens.slint`) and as the library's `SCREENS` (`screens.rs`), so the order is kept
/// once.
fn screens(table: &std::path::Path, out: &std::path::Path) {
    println!("cargo:rerun-if-changed={}", table.display());
    let text =
        std::fs::read_to_string(table).unwrap_or_else(|e| panic!("{}: {e}", table.display()));
    let rows: Vec<(&str, &str)> = text
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
        .map(|l| {
            l.split_once('\t')
                .unwrap_or_else(|| panic!("screens.tsv: no detail in {l:?}"))
        })
        .collect();
    let mut slint = String::from(
        "// @generated by build.rs from screens.tsv: the list of the activity's screens.\n\
         import { ListLine } from \"@blackbird/slint/components.slint\";\n\n\
         export component ScreenList inherits VerticalLayout {\n    \
         in property <float> unit;\n    callback open(string);\n    alignment: start;\n",
    );
    let mut rust = String::from(
        "/// The activity's screens, in the order its list shows them (generated from screens.tsv).\n\
         pub const SCREENS: &[&str] = &[\n",
    );
    for (i, (name, detail)) in rows.iter().enumerate() {
        assert!(
            !name.contains('"') && !detail.contains('"'),
            "screens.tsv: a quote in {name}"
        );
        // Focus on entry (design system §8.4): the list's first element.
        let init = if i == 0 {
            " init => { self.focus(); }"
        } else {
            ""
        };
        slint.push_str(&format!(
            "    ListLine {{ label: \"{name}\"; detail: \"{detail}\"; unit: root.unit; clicked => {{ root.open(\"{name}\"); }}{init} }}\n"
        ));
        rust.push_str(&format!("    {name:?},\n"));
    }
    slint.push_str("}\n");
    rust.push_str("];\n");
    std::fs::write(out.join("screens.slint"), slint).unwrap();
    std::fs::write(out.join("screens.rs"), rust).unwrap();
}
