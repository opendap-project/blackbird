"""Generate the platform outputs of the design tokens (tokens README, design system §18.1).

opendap.tokens.json is the single source. This script writes, and nobody edits by hand:
  ../export/slint/tokens.slint  `export global Tokens` for Blackbird OS (Slint)
  ../export/css/tokens.css      `:root` custom properties for web, documentation and OpenDAP Desktop

Names are the token path joined with "-": color.graphite.950 -> color-graphite-950,
semantic.text.primary -> text-primary (the "semantic" prefix is dropped, as in the spec's CSS).
Aliases ({a.b}) are resolved. Types a target cannot express are skipped there and listed in
the file's header: in Slint, shadows and gradients (they are drawn by components, §18.1).

Run: python3 generate.py            write both outputs
     python3 generate.py --check    exit 1 if the outputs are not up to date
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE / "opendap.tokens.json"
OUT = HERE.parent / "export"


def load():
    return json.loads(SOURCE.read_text())


def flatten(node, path=(), inherited=None):
    """Yield (path, type, value) for every token, with the group's $type inherited."""
    kind = node.get("$type", inherited)
    for key, child in node.items():
        if key.startswith("$") or not isinstance(child, dict):
            continue
        if "$value" in child:
            yield path + (key,), child.get("$type", kind), child["$value"]
        else:
            yield from flatten(child, path + (key,), kind)


def resolve(tokens):
    by_path = {".".join(p): (t, v) for p, t, v in tokens}

    def follow(value, seen=()):
        if isinstance(value, str) and value.startswith("{") and value.endswith("}"):
            ref = value[1:-1]
            if ref in seen or ref not in by_path:
                raise SystemExit(f"unresolved alias {value}")
            return follow(by_path[ref][1], seen + (ref,))
        return value

    return [(p, t, follow(v)) for p, t, v in tokens]


def name(path):
    parts = path[1:] if path[0] == "semantic" else path
    return "-".join(parts)


def hex_of(value):
    h = value["hex"]
    alpha = value.get("alpha")
    if alpha is not None and alpha < 1:
        h += f"{round(alpha * 255):02X}"
    return h


def slint_value(kind, value):
    if kind == "color":
        return "color", hex_of(value)
    if kind == "dimension":
        return "length", f"{value['value']}px"
    if kind == "duration":
        return "duration", f"{value['value']}ms"
    if kind == "fontWeight":
        return "int", str(value)
    if kind == "fontFamily":
        return "string", json.dumps(value[0])
    if kind == "number":
        return "float", str(value)
    return None


def css_value(kind, value):
    if kind == "color":
        return hex_of(value)
    if kind == "dimension":
        return f"{value['value']}{value['unit']}"
    if kind == "duration":
        return f"{value['value']}{value['unit']}"
    if kind == "fontWeight":
        return str(value)
    if kind == "fontFamily":
        return ", ".join(f'"{f}"' if " " in f else f for f in value)
    if kind == "number":
        return str(value)
    if kind == "cubicBezier":
        return "cubic-bezier({})".format(", ".join(str(x) for x in value))
    if kind == "shadow":
        c = hex_of(value["color"])
        return " ".join(f"{value[k]['value']}{value[k]['unit']}" for k in ("offsetX", "offsetY", "blur", "spread")) + f" {c}"
    return None


def header(comment, skipped, version):
    # REUSE-IgnoreStart
    lines = [
        "SPDX-FileCopyrightText: 2026 The OpenDAP Project",
        "SPDX-License-Identifier: MPL-2.0",
        f"Generated by blackbird-ui/tokens/generate.py from opendap.tokens.json (theme {version}). Do not edit.",
    ]
    # REUSE-IgnoreEnd
    if skipped:
        lines.append("Not expressible here, drawn by components: " + ", ".join(skipped))
    return "".join(f"{comment} {line}\n" for line in lines)


def generate():
    source = load()
    version = source["$extensions"]["org.opendap.theme"]["version"]
    tokens = resolve(list(flatten(source)))

    slint, slint_skipped = [], []
    css, css_skipped = [], []
    for path, kind, value in tokens:
        n = name(path)
        sv = slint_value(kind, value)
        if sv:
            slint.append(f"    out property <{sv[0]}> {n}: {sv[1]};")
        else:
            slint_skipped.append(n)
        cv = css_value(kind, value)
        if cv:
            css.append(f"  --{n}: {cv};")
        else:
            css_skipped.append(n)

    slint_text = header("//", slint_skipped, version) + "\nexport global Tokens {\n" + "\n".join(slint) + "\n}\n"
    css_text = "/*\n" + header("  ", css_skipped, version) + "*/\n:root {\n" + "\n".join(css) + "\n}\n"
    return {OUT / "slint" / "tokens.slint": slint_text, OUT / "css" / "tokens.css": css_text}


def main():
    outputs = generate()
    if "--check" in sys.argv:
        stale = [str(p) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("out of date: " + ", ".join(stale), file=sys.stderr)
            sys.exit(1)
        return
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(path.relative_to(HERE.parent))


if __name__ == "__main__":
    main()
